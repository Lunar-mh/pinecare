-- 003-medication-reminder: 创建用药提醒设置表

CREATE TABLE IF NOT EXISTS medication_settings (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT NOT NULL,
  reminder_enabled TINYINT(1) NOT NULL DEFAULT 1,
  family_sync_enabled TINYINT(1) NOT NULL DEFAULT 0,
  sleep_start TIME NOT NULL DEFAULT '22:00:00',
  sleep_end TIME NOT NULL DEFAULT '06:00:00',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
